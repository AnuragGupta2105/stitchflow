
import { Router } from "express";
import { z } from "zod";

import {
  ProductionStage,
  UserRole,
} from "../../generated/prisma/client";

import { prisma } from "../config/database";

import {
  requireAuth,
  allowRoles,
} from "../middleware/auth.middleware";

import type {
  AuthenticatedRequest,
} from "../middleware/auth.middleware";

const router = Router();

// --------------------------------------------------
// VALIDATION
// --------------------------------------------------

const updateSchema = z.object({
  orderId: z.string().min(1),

  stage: z.nativeEnum(ProductionStage),

  quantity: z.number().int().positive(),

  issueNote: z.string().max(2000).optional(),

  photoUrl: z.string().url().optional(),

  // Stable UUID generated by the frontend for each submission.
  // The same ID must be reused when an offline item is retried.
  clientRequestId: z.string().uuid().optional(),
});

// --------------------------------------------------
// IDEMPOTENCY HELPERS
// --------------------------------------------------

function isUniqueConstraintError(error: unknown): boolean {
  return (
    typeof error === "object" &&
    error !== null &&
    "code" in error &&
    error.code === "P2002"
  );
}

// --------------------------------------------------
// POST: SUBMIT DAILY PRODUCTION UPDATE
// Supervisor only.
// Supports safe retries from the offline queue.
// --------------------------------------------------

router.post(
  "/",
  requireAuth,
  allowRoles(UserRole.SUPERVISOR),
  async (req, res) => {
    try {
      const authReq = req as AuthenticatedRequest;
      const user = authReq.user;

      if (!user || !user.unitId) {
        return res.status(403).json({
          message:
            "Supervisor is not assigned to a production unit",
        });
      }

      // Validate submitted data.
      const validation = updateSchema.safeParse(req.body);

      if (!validation.success) {
        return res.status(400).json({
          message: "Invalid production update",
          errors: validation.error.flatten(),
        });
      }

      const {
        orderId,
        stage,
        quantity,
        issueNote,
        photoUrl,
        clientRequestId,
      } = validation.data;

      // Verify that the selected order exists.
      const order = await prisma.order.findUnique({
        where: {
          id: orderId,
        },
        select: {
          id: true,
          unitName: true,
        },
      });

      if (!order) {
        return res.status(404).json({
          message: "Order not found",
        });
      }

      // Supervisor can only submit reports for their own unit.
      if (order.unitName !== user.unitId) {
        return res.status(403).json({
          message:
            "You cannot update an order assigned to another unit",
        });
      }

      // --------------------------------------------------
      // CHECK WHETHER THIS OFFLINE REQUEST WAS ALREADY SAVED
      // --------------------------------------------------

      if (clientRequestId) {
        const existingUpdate =
          await prisma.productionUpdate.findUnique({
            where: {
              clientRequestId,
            },
          });

        if (existingUpdate) {
          // Prevent another user or order from reusing this ID.
          if (
            existingUpdate.userId !== user.id ||
            existingUpdate.orderId !== orderId
          ) {
            return res.status(409).json({
              message:
                "This request ID has already been used by another submission",
            });
          }

          // Make sure the core report information matches.
          const sameSubmission =
            existingUpdate.stage === stage &&
            existingUpdate.quantity === quantity &&
            existingUpdate.issueNote === (issueNote ?? null);

          if (!sameSubmission) {
            return res.status(409).json({
              message:
                "The request ID was reused with different production data",
            });
          }

          return res.status(200).json({
            success: true,
            duplicate: true,
            message:
              "Production update was already received. No duplicate was created.",
            update: existingUpdate,
          });
        }
      }

      // --------------------------------------------------
      // CREATE THE PRODUCTION UPDATE
      // --------------------------------------------------

      try {
        const update = await prisma.productionUpdate.create({
          data: {
            orderId,
            userId: user.id,
            stage,
            quantity,
            issueNote: issueNote ?? null,
            photoUrl: photoUrl ?? null,
            clientRequestId: clientRequestId ?? null,
          },
        });

        return res.status(201).json({
          success: true,
          duplicate: false,
          message: "Production update submitted successfully",
          update,
        });
      } catch (createError) {
        // Handle simultaneous retries that arrive together.
        // The database unique constraint ensures only one is saved.
        if (clientRequestId && isUniqueConstraintError(createError)) {
          const existingUpdate =
            await prisma.productionUpdate.findUnique({
              where: {
                clientRequestId,
              },
            });

          if (
            existingUpdate &&
            existingUpdate.userId === user.id &&
            existingUpdate.orderId === orderId &&
            existingUpdate.stage === stage &&
            existingUpdate.quantity === quantity &&
            existingUpdate.issueNote === (issueNote ?? null)
          ) {
            return res.status(200).json({
              success: true,
              duplicate: true,
              message:
                "Production update was already received. No duplicate was created.",
              update: existingUpdate,
            });
          }

          return res.status(409).json({
            message:
              "Unable to process this request ID. Please verify the submission.",
          });
        }

        throw createError;
      }
    } catch (error) {
      console.error("Production update error:", error);

      return res.status(500).json({
        success: false,
        message: "Unable to submit production update",
      });
    }
  }
);

// --------------------------------------------------
// GET: FETCH PRODUCTION UPDATE HISTORY
//
// Supervisor: only their assigned unit.
// Merchandiser: all units.
// --------------------------------------------------

router.get(
  "/history",
  requireAuth,
  allowRoles(
    UserRole.SUPERVISOR,
    UserRole.MERCHANDISER
  ),
  async (req, res) => {
    try {
      const authReq = req as AuthenticatedRequest;
      const user = authReq.user;

      if (!user) {
        return res.status(401).json({
          message: "Authentication required",
        });
      }

      // Supervisors must have an assigned unit.
      if (
        user.role === UserRole.SUPERVISOR &&
        !user.unitId
      ) {
        return res.status(403).json({
          message:
            "Supervisor is not assigned to a production unit",
        });
      }

      // Supervisors see their own unit only.
      // Merchandisers see all production history.
      const where =
        user.role === UserRole.SUPERVISOR
          ? {
              order: {
                unitName: user.unitId!,
              },
            }
          : {};

      // Fetch the latest 50 updates.
      const updates = await prisma.productionUpdate.findMany({
        where,

        orderBy: {
          createdAt: "desc",
        },

        take: 50,

        include: {
          user: {
            select: {
              name: true,
            },
          },

          order: {
            select: {
              poNumber: true,
              unitName: true,
            },
          },

          reasonAnalysis: true,
        },
      });

      return res.json({
        success: true,
        count: updates.length,
        updates,
      });
    } catch (error) {
      console.error("Production history error:", error);

      return res.status(500).json({
        success: false,
        message: "Failed to fetch production history",
      });
    }
  }
);

export default router;
